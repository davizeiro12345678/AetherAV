#!/usr/bin/env python3
"""Fail-closed evaluation of NEW, hash-disjoint, real-file AV holdout verdicts.

Consume verdicts generated by a separately isolated scanner. This script never
opens malware bytes, downloads samples, runs executables or changes quarantine.
No report may claim independent certification from self-declared flags alone.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import sys

from detection_quality_gate import evaluate as quality_evaluate

_SHA=re.compile(r"^[a-f0-9]{64}$")


def _hash(v):
    if not isinstance(v,str) or not _SHA.fullmatch(v):
        raise ValueError("invalid lowercase sample SHA-256")
    return v


def evaluate_holdout(rows:list[dict], manifest:dict, excluded_hashes:set[str]) -> dict:
    if not isinstance(rows,list) or not rows:
        raise ValueError("nonempty per-file verdicts are required")
    if not isinstance(manifest,dict):
        raise ValueError("manifest object required")
    expected=_hash(manifest.get("engine_sha256"))
    if not isinstance(excluded_hashes,set):
        raise ValueError("excluded set required")
    for h in excluded_hashes:
        _hash(h)
    seen=set()
    tp=fp=fn=tn=0
    blocked=0
    suspicious=0
    for row in rows:
        if not isinstance(row,dict):
            raise ValueError("record must be an object")
        key=_hash(row.get("sha256"))
        if key in seen:
            raise ValueError("duplicate sample SHA-256 in holdout")
        if key in excluded_hashes:
            raise ValueError("holdout overlaps train, validation or prior tests")
        seen.add(key)
        if row.get("engine_sha256")!=expected:
            raise ValueError("record does not match pinned engine binary")
        if row.get("sample_kind")!="real_file":
            raise ValueError("only real scanned files qualify")
        label=row.get("label")
        verdict=row.get("verdict")
        if label not in {"benign","malicious"} or verdict not in {"CLEAN","SUSPICIOUS","MALICIOUS"}:
            raise ValueError("missing/invalid label or verdict; scanner errors must fail")
        detected=verdict!="CLEAN"
        suspicious+=int(verdict=="SUSPICIOUS")
        blocked+=int(row.get("blocked") is True)
        if label=="malicious":
            tp+=int(detected);fn+=int(not detected)
        else:
            fp+=int(detected);tn+=int(not detected)
    provenance={
        "independent_new_holdout":(
            manifest.get("test_new_and_independent") is True
            and bool(excluded_hashes) and bool(manifest.get("auditor_id"))),
        "sample_hashes_deduplicated":True,
        "train_validation_test_disjoint":bool(excluded_hashes),
        "labels_verified":(
            manifest.get("labels_audited") is True and bool(manifest.get("auditor_id"))),
        "shipping_engine_equivalent":(
            manifest.get("engine_binary_verified") is True
            and manifest.get("all_production_engines_enabled") is True
            and manifest.get("signatures_verified") is True
            and manifest.get("network_isolated") is True
            and manifest.get("host_fs_not_mounted") is True),
        "threshold_chosen_without_test":manifest.get("threshold_preselected") is True,
        "corpus_identifier":str(manifest.get("corpus_identifier") or "UNSPECIFIED"),
    }
    result=quality_evaluate({"confusion":{"tp":tp,"fp":fp,"fn":fn,"tn":tn},
                            "provenance":provenance})
    result["caveat"]="Auditor identity and manifest flags are declarations requiring independent external verification."
    return {
        "engine_sha256":expected,
        "corpus_identifier":provenance["corpus_identifier"],
        "sample_count":len(rows),
        "excluded_reference_hashes_count":len(excluded_hashes),
        "confusion":{"tp":tp,"fn":fn,"fp":fp,"tn":tn},
        "suspicious_verdicts_count":suspicious,
        "samples_reported_blocked":blocked,
        "quality_gate":result,
        "test_reused":not provenance["independent_new_holdout"],
        "certified_by_external_auditor":False,
    }


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest",required=True,type=Path)
    ap.add_argument("--verdicts",required=True,type=Path,help="JSONL of real-file sample verdicts")
    ap.add_argument("--excluded-hashes",required=True,type=Path,
                    help="SHA-256 lines from ALL train, validation and all previously consulted test sets")
    ap.add_argument("--out",required=True,type=Path)
    a=ap.parse_args()
    try:
        rows=[json.loads(line) for line in a.verdicts.read_text().splitlines() if line.strip()]
        excluded=set(line.strip() for line in a.excluded_hashes.read_text().splitlines() if line.strip())
        report=evaluate_holdout(rows,json.loads(a.manifest.read_text()),excluded)
        a.out.write_text(json.dumps(report,indent=2)+"\n")
        print(json.dumps({"approved":report["quality_gate"]["release_eligible"],
                          "confusion":report["confusion"],"out":str(a.out)}))
        return 0 if report["quality_gate"]["release_eligible"] else 1
    except (ValueError,KeyError,TypeError,OSError,json.JSONDecodeError) as err:
        print("Holdout evidence rejected: "+str(err),file=sys.stderr)
        return 2

if __name__=="__main__":
    raise SystemExit(main())
